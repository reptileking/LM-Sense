"""Structural vocabulary: reserved-range token ids, append-only registry and documentation.

``python -m senselm.inventory.structural --config configs/structural.yaml``

Each category of configs/structural.yaml owns one reserved lemma slot; item *i* of category
slot *s* has ``token_id = ((STRUCTURAL_LEMMA_BASE + s) << SENSE_BITS) | i`` where
STRUCTURAL_LEMMA_BASE = 2**22 - 4096 (so ids start at 0xFFC00000). Generated categories:
``bytes`` (indices 0-255 = byte values, listed items follow) and ``digits`` (0-9).

The registry is append-only like the lexical one: an existing (category, name) keeps its id;
items may be retired (status = deprecated) but never removed or renumbered.
"""

from __future__ import annotations

import logging
from typing import Any

import polars as pl

from senselm.common import Provenance, load_config, resolve, stage_args, write_table
from senselm.inventory.ids import Layout

LOG = logging.getLogger("senselm.inventory.structural")
SCHEMA = {
    "token_id": pl.UInt32,
    "category": pl.String,
    "slot": pl.UInt16,
    "index": pl.UInt16,
    "name": pl.String,
    "token": pl.String,
    "description": pl.String,
    "status": pl.String,
    "created_in": pl.String,
}


def spec_items(cat: dict[str, Any]) -> list[tuple[int | None, str, str]]:
    """(fixed index or None, name, description) in declaration order."""
    out: list[tuple[int | None, str, str]] = []
    if cat.get("generate") == "bytes":
        out += [(b, f"0x{b:02X}", f"byte value {b}") for b in range(256)]
    if cat.get("generate") == "digits":
        out += [(None, str(d), f"digit {d}") for d in range(10)]
    out += [(None, str(n), str(d)) for n, d in cat.get("items", [])]
    return out


def build(
    cfg: dict[str, Any], prev: pl.DataFrame | None, layout: Layout | None = None
) -> pl.DataFrame:
    layout = layout or Layout()
    base_lemma = (1 << layout.lemma_bits) - layout.reserved_lemma_slots
    prev = prev if prev is not None else pl.DataFrame(schema=SCHEMA)
    known = {(r["category"], r["name"]): r for r in prev.to_dicts()}
    rows: list[dict[str, Any]] = []
    seen_slots: dict[int, str] = {}
    for cat in cfg["categories"]:
        slot = int(cat["slot"])
        if slot in seen_slots or not 0 <= slot < layout.reserved_lemma_slots:
            raise ValueError(f"bad or duplicate slot {slot} for {cat['name']}")
        seen_slots[slot] = cat["name"]
        used = {r["index"] for r in prev.to_dicts() if r["slot"] == slot}
        nxt = max(used) + 1 if used else 0
        for fixed, name, desc in spec_items(cat):
            old = known.pop((cat["name"], name), None)
            if old is not None:
                rows.append({**old, "description": desc})
                continue
            if fixed is not None:
                idx = fixed
            else:
                idx = max(nxt, 256 if cat.get("generate") == "bytes" else 0)
                nxt = idx + 1
            if idx > layout.max_sense_index:
                raise OverflowError(f"category {cat['name']} is full")
            tid = ((base_lemma + slot) << layout.sense_bits) | idx
            rows.append(
                {
                    "token_id": tid,
                    "category": cat["name"],
                    "slot": slot,
                    "index": idx,
                    "name": name,
                    "token": f"<{name}>" if cat["name"] == "special" else f"<{cat['name']}:{name}>",
                    "description": desc,
                    "status": "active",
                    "created_in": cat.get("created_in", cfg["build_id"]),
                }
            )
            if fixed is None:
                nxt = max(nxt, idx + 1)
    for old in known.values():  # removed from the spec: tombstone, never delete
        rows.append({**old, "status": "deprecated"})
    df = pl.DataFrame(rows, schema=SCHEMA).sort("token_id")
    if df["token_id"].n_unique() != df.height:
        raise RuntimeError("structural token id collision")
    if not all(layout.is_structural(t) for t in df["token_id"].to_list()):
        raise RuntimeError("structural token outside the reserved range")
    return df


def markdown(cfg: dict[str, Any], df: pl.DataFrame) -> str:
    lines = [
        "# Structural tokens",
        "",
        "Generated by `python -m senselm.inventory.structural --config configs/structural.yaml` from",
        "`configs/structural.yaml`. Token ids live in the reserved range `0xFFC00000`–`0xFFFFFFFF`",
        "(top 4,096 lemma slots of the 22 + 10-bit layout). Each category owns one slot (1,024 ids);",
        "ids are permanent and append-only.",
        "",
        f"Total: **{df.filter(pl.col('status') == 'active').height}** active structural tokens.",
        "",
        "| category | slot | first id | tokens | purpose |",
        "|---|---|---|---|---|",
    ]
    for cat in cfg["categories"]:
        sub = df.filter(pl.col("category") == cat["name"])
        lines.append(
            f"| {cat['name']} | {cat['slot']} | `0x{sub['token_id'].min():08X}` | {sub.height} | "
            f"{' '.join(cat['description'].split())} |"
        )
    lines += [
        "",
        "## Conventions",
        "",
        "* **Order inside a word**: `[case] [variant] SENSE [morph features…]`, e.g. "
        '`<case:cap> run <morph:PST>` → "Ran".',
        "* **Morphology** uses UniMorph feature names; features are atomic tokens emitted after "
        "the sense token, in schema order (tense/aspect, mood, voice, person, number, degree, "
        "finiteness, case, gender, polarity). Unmarked = the lemma form.",
        "* **Byte fallback**: `<byte:bytes_start>` UTF-8 bytes `<byte:bytes_end>`; a byte span is "
        "one orthographic word (spacing rules apply around it).",
        "* **Numbers** are digit tokens with punctuation tokens for separators: 3.14 → "
        "`<digit:3> <punct:.> <digit:1> <digit:4>`.",
        "* **Spacing** defaults to one space between words and none before closing punctuation; "
        "`<space:…>` tokens override it.",
        "",
        "## All tokens",
        "",
        "| token_id | token | description |",
        "|---|---|---|",
    ]
    for r in df.filter(pl.col("category") != "byte").iter_rows(named=True):
        tok = r["token"].replace("|", "\\|").replace("`", "\\`")
        lines.append(f"| `0x{r['token_id']:08X}` | `{tok}` | {r['description']} |")
    lines += ["", "Byte tokens `<byte:0x00>`…`<byte:0xFF>` occupy indices 0–255 of slot 1.", ""]
    return "\n".join(lines)


def run(cfg: dict[str, Any]) -> dict[str, Any]:
    reg_path = resolve(cfg["registry"])
    commit = resolve(cfg["registry_commit"])
    prev = None
    for p in (reg_path, commit):
        if p.exists():
            prev = pl.read_parquet(p).cast(SCHEMA)
            break
    df = build(cfg, prev)
    if prev is not None:
        j = prev.join(df, on="token_id", how="left", suffix="_new")
        if j.filter(pl.col("name_new").is_null() | (pl.col("name") != pl.col("name_new"))).height:
            raise RuntimeError("structural registry would change an existing id")
    prov = Provenance(stage="inventory.structural", config=cfg)
    st = {
        "active": df.filter(pl.col("status") == "active").height,
        "by_category": dict(df.group_by("category").len().sort("category").iter_rows()),
    }
    for p in (reg_path, commit):
        write_table(df.to_arrow(), p, prov, stats=st)
    resolve(cfg["doc_output"]).write_text(markdown(cfg, df), encoding="utf-8")
    LOG.info("structural: %s", st)
    return st


def main() -> None:
    args = stage_args("Build the structural-token registry")
    run(load_config(args.config))


if __name__ == "__main__":
    main()
